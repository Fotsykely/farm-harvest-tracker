using Api.Entities;
using Microsoft.EntityFrameworkCore;

namespace Api.Data;

public class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public DbSet<Plot> Plots => Set<Plot>();
    public DbSet<Harvest> Harvests => Set<Harvest>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Plot>(plot =>
        {
            plot.Property(p => p.Name).HasMaxLength(Plot.NameMaxLength);
            plot.HasIndex(p => p.Name).IsUnique();

            // The six plots of the cooperative, inserted by the migration. Ids are explicit so that
            // the order of the list never depends on the insertion order.
            plot.HasData(
                new Plot { Id = 1, Name = "Parcelle Nord" },
                new Plot { Id = 2, Name = "Parcelle Sud" },
                new Plot { Id = 3, Name = "Verger" },
                new Plot { Id = 4, Name = "Potager" },
                new Plot { Id = 5, Name = "Colline" },
                new Plot { Id = 6, Name = "Bas-fond" });
        });

        modelBuilder.Entity<Harvest>(harvest =>
        {
            harvest.Property(h => h.RiceKg).HasPrecision(10, 2);
            harvest.Property(h => h.MaizeKg).HasPrecision(10, 2);
            harvest.Property(h => h.CassavaKg).HasPrecision(10, 2);

            // The creation date is generated by MySQL, not by application code.
            harvest.Property(h => h.CreatedAt).HasDefaultValueSql("CURRENT_TIMESTAMP(6)");

            // One entry per plot and per month.
            harvest.HasIndex(h => new { h.PlotId, h.Year, h.Month }).IsUnique();

            harvest.HasOne(h => h.Plot).WithMany().HasForeignKey(h => h.PlotId).OnDelete(DeleteBehavior.Restrict);
        });
    }
}
